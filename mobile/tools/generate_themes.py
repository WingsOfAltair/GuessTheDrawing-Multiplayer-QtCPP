"""Keep native palettes and Android widget/dialog themes aligned with the Qt client."""
from pathlib import Path
import json

root = Path(__file__).resolve().parents[1]
palettes = json.loads((root / 'fixtures/themes.json').read_text())
keys = ['window', 'surface', 'base', 'text', 'accent', 'accentText', 'button', 'disabledText']
kt = ['package com.guessthedrawing.mobile', '', '// Generated by tools/generate_themes.py. Colors match MainWindow::applyTheme.',
      'data class ThemePalette(val id: String, val name: String, ' + ', '.join('val '+k+': Int' for k in keys) + ') {',
      '    val dark get() = ((window shr 16 and 255)*299 + (window shr 8 and 255)*587 + (window and 255)*114) < 128000',
      '    companion object {', '        val all = listOf(']
sw = ['import Foundation', '', '// Generated by tools/generate_themes.py. Colors match MainWindow::applyTheme.',
      'struct ThemePalette {', '    let id: String; let name: String', '    ' + '; '.join('let '+k+': String' for k in keys),
      '    var dark: Bool {', '        let v = Int(window.dropFirst(), radix: 16) ?? 0',
      '        return ((v >> 16 & 255)*299 + (v >> 8 & 255)*587 + (v & 255)*114) < 128000', '    }',
      '    static let all: [ThemePalette] = [']
xml = ['<resources>', '    <!-- Generated by tools/generate_themes.py. -->',
       '    <style name="AppTheme" parent="android:style/Theme.Material.Light.NoActionBar" />']
for p in palettes:
    colors = p['colors']
    kt.append('            ThemePalette(' + ', '.join([json.dumps(p['id']), json.dumps(p['name'])] + ['0xff'+c[1:]+'.toInt()' for c in colors]) + '),')
    sw.append('        ThemePalette(' + ', '.join(k+': '+json.dumps(v) for k,v in zip(['id','name']+keys,[p['id'],p['name']]+colors)) + '),')
    name = p['id'].replace('-', '_')
    light = p['id'] in ['light','rose']
    for dialog in [False, True]:
        style = 'Gtd_' + name + ('_Dialog' if dialog else '')
        parent = 'android:style/Theme.Material' + ('.Light' if light else '') + ('.Dialog.Alert' if dialog else '.NoActionBar')
        xml.append(f'    <style name="{style}" parent="{parent}">')
        values = {'fontFamily':'sans', 'colorBackground':colors[0], 'windowBackground':colors[0],
                  'colorAccent':colors[4], 'textColorPrimary':colors[3], 'textColorSecondary':colors[7],
                  'textColorHint':colors[7], 'colorControlNormal':colors[7], 'colorControlActivated':colors[4],
                  'colorButtonNormal':colors[6], 'windowLightStatusBar':str(light).lower(),
                  'navigationBarColor':colors[0], 'statusBarColor':colors[0]}
        if not dialog: values['alertDialogTheme'] = '@style/Gtd_'+name+'_Dialog'
        for key,value in values.items(): xml.append(f'        <item name="android:{key}">{value}</item>')
        xml.append('    </style>')
kt += ['        )', '    }', '}']
sw += ['    ]', '}']
xml += ['</resources>']
for path, lines in [
    ('android/app/src/main/java/com/guessthedrawing/mobile/ThemePalette.kt', kt),
    ('ios/GuessTheDrawing/Core/ThemePalette.swift', sw),
    ('android/app/src/main/res/values/styles.xml', xml)]:
    (root / path).write_text('\n'.join(lines)+'\n', encoding='utf-8')
print('Generated 13 palettes plus platform System theme')
