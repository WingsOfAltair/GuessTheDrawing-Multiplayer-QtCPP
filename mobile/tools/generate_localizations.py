"""Generate native Android and iOS resources from the shared, reviewed catalog."""
from pathlib import Path
import argparse, hashlib, json, re
from xml.sax.saxutils import escape

root = Path(__file__).resolve().parents[1]
folder = root/'localization'
parser = argparse.ArgumentParser()
parser.add_argument('--allow-incomplete', action='store_true', help='Development only: report missing translations and temporarily use English')
args = parser.parse_args()
languages = ['en','es','fr','de','pt','it','ru','zh','ja','ko','ar','hi']
catalog = json.loads((folder/'desktop.json').read_text(encoding='utf-8'))
for line in (line for path in sorted(folder.glob('*.tsv')) for line in path.read_text(encoding='utf-8').splitlines()):
    if not line or line.startswith('#'): continue
    cells = [cell.replace('\\n','\n') for cell in line.split('|')]
    assert len(cells)==12, (len(cells),cells[0])
    for code,value in zip(languages,cells):
        assert value, (cells[0],code)
        catalog[code][cells[0]]=value
aliases=json.loads((folder/'aliases.json').read_text(encoding='utf-8'))
compositions=json.loads((folder/'compositions.json').read_text(encoding='utf-8'))
for _ in range(len(aliases)+1):
    for source,template in compositions.items():
        for code in languages:
            names=re.findall(r'\[\[(.*?)\]\]',template)
            if all(name in catalog[code] for name in names):
                catalog[code][source]=source if code=='en' else re.sub(r'\[\[(.*?)\]\]',lambda m:catalog[code][m[1]],template)
    for source,target in aliases.items():
        for code in languages:
            if target in catalog[code]:catalog[code][source]=source if code=='en' else catalog[code][target]
required=json.loads((folder/'required.json').read_text(encoding='utf-8'))
missing=[]
for source in required:
    catalog['en'][source]=source
    for code in languages[1:]:
        if source not in catalog[code]:missing.append((code,source)); catalog[code][source]=source
if missing:
    (folder/'missing.txt').write_text('\n'.join(f'{code}: {source}' for code,source in missing),encoding='utf-8')
    print(f'{len(missing)} translations missing ({len(set(source for _,source in missing))} English keys)')
    if not args.allow_incomplete:raise SystemExit('Complete the shared translation catalog before generating release resources.')
elif (folder/'missing.txt').exists():(folder/'missing.txt').unlink()
keys=sorted(catalog['en'])
# Isolate Latin product names and literal IP addresses inside Arabic prose.
# Dynamic values receive the same Unicode isolation in the two native formatters.
latin = re.compile(r'[A-Za-z][A-Za-z0-9]*(?:[ /><:.-]+[A-Za-z0-9]+)*|(?:\d{1,3}\.){3}\d{1,3}')
catalog['ar'] = {key:latin.sub(lambda m:'\u2068'+m[0]+'\u2069',value) for key,value in catalog['ar'].items()}
ids={key:'l_'+hashlib.sha1(key.encode()).hexdigest()[:12] for key in keys}
def string(value):return json.dumps(value,ensure_ascii=False)
for code in languages:
    for source in keys:
        assert source in catalog[code],(code,source)
        assert set(re.findall(r'%\d+',catalog[code][source])) <= set(re.findall(r'%\d+',source)),(code,source,catalog[code][source])
    values='values' if code=='en' else 'values-'+('zh-rCN' if code=='zh' else code)
    target=root/'android/app/src/main/res'/values/'strings.xml'; target.parent.mkdir(parents=True,exist_ok=True)
    lines=['<?xml version="1.0" encoding="utf-8"?>','<!-- Generated by tools/generate_localizations.py. -->','<resources>']
    for key in keys:
        value=catalog[code][key].replace('\\','\\\\').replace('\n','\\n').replace('\r','\\r').replace("'","\\'").replace('"','\\"')
        lines.append(f'    <string name="{ids[key]}" formatted="false">"{escape(value)}"</string>')
    lines.append('</resources>'); target.write_text('\n'.join(lines)+'\n',encoding='utf-8')
    loc=root/'ios/GuessTheDrawing'/('zh-Hans' if code=='zh' else code).replace('_','-')
    loc=loc.with_name(loc.name+'.lproj'); loc.mkdir(exist_ok=True)
    (loc/'Localizable.strings').write_text('// Generated from mobile/localization.\n'+'\n'.join(f'{string(k)} = {string(catalog[code][k])};' for k in keys)+'\n',encoding='utf-8')
    info={name:catalog[code].get(source,source) for name,source in {
        'CFBundleDisplayName':'Guess The Drawing',
        'NSLocalNetworkUsageDescription':'Find and connect to your Guess The Drawing master and room servers on the local network.',
        'NSMicrophoneUsageDescription':'Talk with other players when you turn on your microphone in a room.',
        'NSPhotoLibraryAddUsageDescription':'Save a drawing when you choose Save Image from the share sheet.'}.items()}
    (loc/'InfoPlist.strings').write_text('\n'.join(f'{string(k)} = {string(v)};' for k,v in info.items())+'\n',encoding='utf-8')
kt=root/'android/app/src/main/java/com/guessthedrawing/mobile/LocalizationKeys.kt'
kt.write_text('package com.guessthedrawing.mobile\n\n// Generated; edit mobile/localization.\nobject LocalizationKeys {\n    val ids: Map<String, Int> = mapOf(\n'+',\n'.join('        '+string(k).replace('$','\\$')+' to R.string.'+ids[k] for k in keys)+'\n    )\n}\n',encoding='utf-8')
templates=[k for k in keys if '%1' in k and re.search('[A-Za-z]',k)]
sw=root/'ios/GuessTheDrawing/Core/LocalizationKeys.swift'
sw.write_text('// Generated; edit mobile/localization.\nenum LocalizationKeys {\n    static let templates: [String] = [\n'+',\n'.join('        '+string(k) for k in templates)+'\n    ]\n}\n',encoding='utf-8')
(folder/'catalog.json').write_text(json.dumps(catalog,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(f'Generated {len(keys)} strings for {len(languages)} languages on Android and iOS')
